import markUrl from "./assets/mark--dark.svg";

/* Основной знак quietfault — «Пересборка».

   Файл взят из brand/logo/primary/mark--dark.svg байт в байт. Вариант
   `--dark`: цвета зашиты внутрь, поэтому его можно отдавать через <img>.
   `--mono` так нельзя — currentColor через тег картинки не наследуется,
   знак станет чёрным (BRANDBOOK.md §7).

   Знак завёрнут в компонент, чтобы правила брендбука жили в одном месте,
   а не переписывались на каждой вставке:

     минимальный размер на экране — 16px (§2);
     размер кратен 16 — иначе полосы размазывает сглаживанием (§2);
     охранное поле — четверть высоты знака, внутрь не заходит ничто (§2);
     пропорции не меняются, знак не растягивается и не поворачивается (§7).

   Про кратность 16 стоит сказать отдельно, потому что вживую на это легко
   наступить. Высота полосы — 4 единицы сетки 64, то есть size × 4/64.
   При size = 16 это ровно 1px, при 32 — 2px, при 48 — 3px. При «почти том
   же» size = 20 выходит 1.25px, край полосы попадает между пикселями, и
   знак становится мыльным. Сетка в брендбуке нужна ровно для этого.

   Занимаемое поле внутри квадрата 64×64 — 52×40 единиц, то есть по высоте
   знак занимает 40/64 от заданного размера. Охранное поле считается от
   этой высоты, а не от размера квадрата. */

const STEP_PX = 16;

export default function Mark({ size = STEP_PX, title = "quietfault" }) {
  if (size < STEP_PX || size % STEP_PX !== 0) {
    throw new Error(
      `Mark: ${size}px не по сетке. Допустимы 16, 32, 48, 64… — кратные ${STEP_PX}`
    );
  }
  const clear = Math.round((size * (40 / 64)) / 4);
  return (
    <img
      src={markUrl}
      width={size}
      height={size}
      alt={title}
      style={{ display: "block", flexShrink: 0, margin: clear }}
    />
  );
}
