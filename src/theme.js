/* Вычисленные значения — для SVG и canvas.

   var() работает в CSS-свойствах, но НЕ в презентационных атрибутах
   SVG: <line stroke="var(--line)"> просто не отрисуется. recharts
   раскладывает переданные цвета именно в атрибуты, поэтому графикам
   нужны настоящие значения, а не ссылки.

   Читается один раз при первом обращении. Вызывать только во время
   рендера: на момент выполнения модуля стили ещё могут быть не
   применены, и getComputedStyle вернёт пустые строки. */
let cache = null;

export function paint() {
  if (!cache) {
    const cs = getComputedStyle(document.documentElement);
    const v = (name) => cs.getPropertyValue(name).trim();
    cache = {
      line: v("--line"),
      muted: v("--text-dim"),
      text: v("--text"),
      accent: v("--accent"),
      accentHot: v("--accent-hot"),
      /* "249, 115, 22" — для rgba() с переменной прозрачностью:
         тепловая карта задаёт альфу от заполненности дня. */
      accentRGB: v("--accent")
        .replace("#", "")
        .match(/\w\w/g)
        .map((x) => parseInt(x, 16))
        .join(","),
    };
  }
  return cache;
}
